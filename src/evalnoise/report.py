"""Text and Markdown rendering of estimates, plans and study results."""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import Any

LABELS = {
    "item": "item",
    "item_arm": "item x arm",
    "run": "run",
    "item_run": "item x run",
    "within": "within run",
}
COMPONENTS = tuple(LABELS)


def sd(v: float | None) -> float:
    """Standard deviation from a variance estimate, clipping negatives to zero."""
    if v is None or not math.isfinite(v):
        return math.nan
    return math.sqrt(max(v, 0.0))


def fmt(x: float | None, digits: int = 1) -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "-"
    return f"{x:.{digits}f}"


def fmt_ci(lo: float | None, hi: float | None, digits: int = 1) -> str:
    return f"[{fmt(lo, digits)}, {fmt(hi, digits)}]"


def pct(x: float | None) -> str:
    return "-" if x is None or not math.isfinite(x) else f"{100 * x:.0f}%"


def table(header: Sequence[str], rows: Sequence[Sequence[str]], align: str = "") -> str:
    align = align or "l" + "r" * (len(header) - 1)
    marks = ["---:" if a == "r" else "---" for a in align]
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(marks) + " |"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def component_cell(unit: dict[str, Any], name: str, digits: int = 1) -> str:
    comps = unit["components"]
    absorbed = comps.get("absorbed") or {}
    if name in absorbed:
        return f"(in {LABELS[absorbed[name]]})"
    v = comps.get(name)
    if v is None:
        return "n/i"
    if name == "run":
        lo, hi = unit["run_interval"]
    else:
        lo, hi = unit["bootstrap"]["components"][name]
    if v < 0:
        # No SD exists; say so rather than print an exact-looking 0.
        if hi is not None and hi < 0:
            return "<0 [all draws < 0]"
        return f"<0 {fmt_ci(sd(lo), sd(hi), digits)}"
    return f"{fmt(sd(v), digits)} {fmt_ci(sd(lo), sd(hi), digits)}"


def study_markdown(units: list[dict[str, Any]], profile: str) -> str:
    """Summary tables for a study run (all numbers come from the unit files)."""
    parts = [
        "# evalnoise study results",
        "",
        f"Profile `{profile}`. Generated by `evalnoise study`; do not edit by hand.",
        "",
        "Standard deviations (square roots of the variance components) in each dataset's",
        "unit, with 95% intervals: percentile bootstrap over clusters for item-level",
        "components, a chi-square interval for the run component. `n/i`: not identified by",
        "the layout; `(in X)`: folded into component X. `<0`: the moment estimate is",
        "negative (planning uses 0); `all draws < 0`: so was every bootstrap draw, a sign that",
        "the model overstates the noise of cell means there.",
        "",
        "## Datasets",
        "",
    ]
    rows = []
    for u in units:
        c = u["counts"]
        runs = sorted(set(c["runs_per_arm"].values()))
        rows.append(
            [
                f"`{u['id']}`",
                str(c["arms"]),
                str(c["items"]),
                "/".join(map(str, runs)),
                str(c["max_repeats_per_run"]),
                str(c["trials"]),
                u["unit"],
            ]
        )
    parts.append(
        table(["dataset", "arms", "items", "runs per arm", "max repeats", "trials", "unit"], rows)
    )
    parts += ["", "## Variance components (SD)", ""]
    rows = [
        [f"`{u['id']}`"]
        + [component_cell(u, n, u.get("digits", 1)) for n in COMPONENTS]
        + [_icc_item(u)]
        for u in units
    ]
    parts.append(table(["dataset"] + [LABELS[n] for n in COMPONENTS] + ["ICC item"], rows))
    parts += [
        "",
        "ICC item: the item component's share of one trial's variance within an arm (the",
        "correlation between trials of two different arms on the same item); it cancels in",
        "paired comparisons.",
        "",
        "## Run term by arm",
        "",
    ]
    rows = []
    for u in units:
        by_arm = u.get("run_by_arm") or {}
        loo = by_arm.get("leave_one_out", {})
        dg = u.get("digits", 1)
        for arm, x in (by_arm.get("arms") or {}).items():
            rest = loo.get(arm)
            rows.append(
                [
                    f"`{u['id']}`",
                    arm,
                    f"{fmt(sd(x['run']), dg)} {fmt_ci(*_sds(x['run_interval']), dg)}",
                    str(x["run_df"]),
                    f"{fmt(sd(x['item_run']), dg)}",
                    str(x["residual_df"]),
                    f"{fmt(sd(rest['run']), dg)} {fmt_ci(*_sds(rest['run_interval']), dg)}"
                    if rest
                    else "-",
                ]
            )
        hom = by_arm.get("residual_homogeneity")
        if hom:
            p = "-" if hom["p"] is None else f"{hom['p']:.2g}"
            rows.append([f"`{u['id']}`", "Bartlett test, equal item x run", f"p = {p}"] + [""] * 4)
    parts.append(
        table(
            [
                "dataset",
                "arm",
                "run SD [chi-square]",
                "df",
                "item x run SD",
                "df",
                "run SD without this arm",
            ],
            rows,
            "llrrrrr",
        )
    )
    parts += [
        "",
        "Arms with two or more runs, each fitted alone. The pooled run and item x run terms",
        "assume these arms share one variance; the Bartlett test checks that for item x run.",
        "",
        "## Moment estimates vs REML (SD)",
        "",
    ]
    rows = []
    for u in units:
        r = u["reml"]
        for n in COMPONENTS:
            m = u["components"].get(n)
            if m is None or "error" in r:
                continue
            dg = u.get("digits", 1) + 1
            rows.append([f"`{u['id']}`", LABELS[n], fmt(sd(m), dg), fmt(sd(r.get(n)), dg)])
    parts.append(table(["dataset", "component", "moments", "REML"], rows))
    parts += ["", "## Planning: paired comparison, one run per arm", ""]
    rows = []
    for u in units:
        p = u["planning"]
        if "reference_mde" not in p:
            continue
        o = p["reference_design"]
        dg = u.get("digits", 1)
        est = p["run_assumption"] == "estimated"
        fpr = p.get("naive_fpr")
        fpr_ci = p.get("naive_fpr_run_ci", [None, None])
        rows.append(
            [
                f"`{u['id']}`",
                f"{o['tasks']} x {o['repeats']}",
                fmt(p["reference_se_items_only"], dg),
                fmt(p["reference_se"], dg) if est else "-",
                f"{fmt(p['reference_mde'], dg)} {fmt_ci(*p['reference_mde_bootstrap_ci'], dg)}",
                fmt_ci(*p["reference_mde_run_ci"], dg) if est else "-",
                pct(p.get("run_share_of_variance")) if est else "n/i",
                f"{pct(fpr)} [{pct(fpr_ci[0])}, {pct(fpr_ci[1])}]" if est else "n/i",
            ]
        )
    parts.append(
        table(
            [
                "dataset",
                "tasks x repeats",
                "SE, items only",
                "SE with run term",
                "MDE [item bootstrap]",
                "MDE at run CI ends",
                "run share of SE^2",
                "naive false-positive rate [run CI]",
            ],
            rows,
        )
    )
    parts += [
        "",
        "One run per arm, the observed tasks and repeats. SE: of the difference in arm means.",
        "MDE: smallest difference detected with 80% power at alpha 0.05 (two-sided t,",
        "Satterthwaite df). Where identified, the run variance is borrowed from this",
        "dataset with its degrees of freedom, so the MDE is large when the dataset has few",
        "replicate runs. Where it is not identified the MDE assumes it is zero: a lower bound.",
        "Naive false-positive rate: how often a paired test over items, which ignores run",
        "effects, declares a difference between single runs of two identical arms.",
        "",
        "## Tasks per arm needed for a target MDE",
        "",
    ]
    rows = []
    for u in units:
        p = u["planning"]
        for tg, entries in (p.get("targets") or {}).items():
            cells = []
            for e in entries:
                t = e["tasks"]
                cells.append(f"R{e['runs']} K{e['repeats']}: {t if t is not None else 'never'}")
            rows.append([f"`{u['id']}`", f"{tg} {u['unit']}", "; ".join(cells)])
    parts.append(table(["dataset", "target", "tasks needed (R runs, K repeats)"], rows, "lll"))
    parts += [
        "",
        "`never`: the run term alone exceeds the target at that number of runs.",
        "",
        "## Planning notes",
        "",
    ]
    for u in units:
        notes = (u["planning"] or {}).get("notes") or []
        parts += [f"- `{u['id']}`: {n}" for n in notes]
    parts += [
        "",
        "## Pairwise differences",
        "",
    ]
    rows = []
    for u in units:
        dg = u.get("digits", 1)
        for name, pe in u["pair_estimates"].items():
            b = u["bootstrap"]["pairs"].get(name, {})
            rows.append(
                [
                    f"`{u['id']}`",
                    name,
                    f"{fmt(pe['difference'], dg)} {fmt_ci(*b.get('difference', [None, None]), dg)}",
                    fmt(pe["se_items"], dg),
                    fmt(pe.get("se_clusters"), dg),
                    _p(pe.get("p_items")),
                    fmt(pe.get("se_with_run"), dg),
                    f"{fmt(pe.get('df_with_run'), 1)} / {_p(pe.get('p_with_run'))}"
                    if pe.get("se_with_run") is not None
                    else "-",
                    f"{fmt(sd(pe['item_arm']), dg)} {fmt_ci(*_sds(b.get('item_arm')), dg)}",
                ]
            )
    parts.append(
        table(
            [
                "dataset",
                "pair",
                "difference [item bootstrap]",
                "SE, items only",
                "SE, clusters",
                "p, clusters",
                "SE with run term",
                "df / p with run term",
                "item x arm SD",
            ],
            rows,
            "llrrrrrrr",
        )
    )
    parts += [
        "",
        "The bootstrap interval and the item-level SEs ignore run-to-run variation. SE,",
        "clusters: cluster-robust, tested with clusters - 1 df (equals the items-only SE when",
        "each item is its own cluster). Where the run variance is identified, the SE with run",
        "term adds run / R_eff for each arm (R_eff: trials / (items x repeats), so a partial",
        "replicate run counts fractionally), tested with Satterthwaite df using the run",
        "term's own df.",
        "",
    ]
    return "\n".join(parts)


def _p(x: float | None) -> str:
    if x is None or not math.isfinite(x):
        return "-"
    return "<0.001" if x < 0.001 else f"{x:.3f}"


def _sds(pair: Sequence[float | None] | None) -> list[float]:
    return [sd(x) for x in (pair or [None, None])]


def _icc_item(u: dict[str, Any]) -> str:
    s = (u.get("shares") or {}).get("item")
    return f"{s:.2f}" if s is not None else "-"
